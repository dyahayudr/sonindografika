// Estimasi waktu baca (200 kata/menit)
const slugify = (s) => s.toLowerCase().replace(/<[^>]+>/g, '').replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');

articles.forEach((a) => {
  // Beri id pada setiap <h2> dan buat daftar isi
  a.toc = [];
  a.body = a.body.replace(/<h2>(.*?)<\/h2>/g, (m, text) => {
    const id = slugify(text);
    a.toc.push({ id, text: text.replace(/<[^>]+>/g, '') });
    return `<h2 id="${id}">${text}</h2>`;
  });
  const words = a.body.replace(/<[^>]+>/g, ' ').split(/\s+/).filter(Boolean).length;
  a.readMinutes = Math.max(2, Math.round(words / 200));
});

articles.sort((a, b) => b.date.localeCompare(a.date));

